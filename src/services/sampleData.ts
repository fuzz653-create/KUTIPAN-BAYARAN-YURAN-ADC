// Helper to compute payment status based on formulas requested
export function calculatePaymentMetrics(monthlyAmounts: Record<number, number>, monthlyFee: number = 20, currentMonth: number = 10) {
  let totalPaid = 0;
  for (let m = 1; m <= 12; m++) {
    totalPaid += monthlyAmounts[m] || 0;
  }
  // Formula: Jumlah Sepatutnya = Yuran Bulanan x Bilangan Bulan (12 bulan)
  const totalDue = monthlyFee * 12;
  const arrears = Math.max(0, totalDue - totalPaid);

  let status: 'SELESAI' | 'SEBAHAGIAN' | 'TERTUNGGAK' | 'BELUM BAYAR';
  if (arrears === 0) {
    status = 'SELESAI';
  } else if (totalPaid === 0) {
    status = 'BELUM BAYAR';
  } else {
    // Check if behind schedule up to current active month
    const dueToDate = monthlyFee * currentMonth;
    if (totalPaid < dueToDate) {
      status = 'TERTUNGGAK';
    } else {
      status = 'SEBAHAGIAN';
    }
  }

  return { totalPaid, totalDue, arrears, status };
}

